/**
 * Shell hook generation. Hooks only prepend project-local tool directories to
 * PATH for the current shell; they never source project files and never mutate
 * a global profile. Escaping is per shell, and the POSIX/fish generators are
 * paired with a parser so the round trip is testable.
 */

export type HookShell = 'bash' | 'zsh' | 'fish' | 'powershell' | 'cmd';

export const HOOK_MARKER_BEGIN = '# >>> StackManage shell hook >>>';
export const HOOK_MARKER_END = '# <<< StackManage shell hook <<<';
export const HOOK_ENV = 'STACKMANAGE_PROJECT';

export interface HookSpec {
  /** Absolute project directory. */
  readonly projectDirectory: string;
  /** Ordered directories, relative to the project or absolute, prepended to PATH. */
  readonly pathEntries: readonly string[];
}

export type HookResult = { readonly ok: true; readonly content: string } | { readonly ok: false; readonly reason: string };

const POSIX_ABSOLUTE = /^\//;
const WINDOWS_ABSOLUTE = /^[A-Za-z]:[\\/]/;

/** Single-quoted POSIX word: safe for every character except NUL. */
export function shQuote(value: string): string {
  if (value.includes('\0')) throw new Error('NUL not permitted');
  return `'${value.replace(/'/g, `'\\''`)}'`;
}

/** Reverses `shQuote` for the quoted words this module emits. */
export function shUnquote(value: string): string {
  if (value.length < 2 || !value.startsWith("'") || !value.endsWith("'")) throw new Error('not a single-quoted word');
  return value.slice(1, -1).replace(/'\\''/g, "'");
}

/** Double-quoted PowerShell string literal. */
export function psQuoteDouble(value: string): string {
  if (/[\0\r\n]/.test(value)) throw new Error('control characters not permitted');
  return `"${value.replace(/[`"$]/g, ch => `\`${ch}`)}"`;
}

/** fish single-quoted string; only `'` and `\` need escaping. */
export function fishQuote(value: string): string {
  if (/[\0\r\n]/.test(value)) throw new Error('control characters not permitted');
  return `'${value.replace(/([\\'])/g, '\\$1')}'`;
}

export function fishUnquote(value: string): string {
  if (value.length < 2 || !value.startsWith("'") || !value.endsWith("'")) throw new Error('not a single-quoted fish word');
  return value.slice(1, -1).replace(/\\([\\'])/g, '$1');
}

/** cmd.exe quoting; refuses characters cmd cannot represent safely. */
export function cmdQuote(value: string): string {
  if (/[\0\r\n]/.test(value)) throw new Error('control characters not permitted');
  if (/["%^&|<>!]/.test(value)) throw new Error('cmd.exe cannot represent this path safely; use PowerShell');
  return `"${value}"`;
}

function joinEntry(projectDirectory: string, entry: string): string {
  const windows = WINDOWS_ABSOLUTE.test(projectDirectory);
  if (windows && /^[A-Za-z]:[\\/]/.test(entry)) return entry;
  if (!windows && POSIX_ABSOLUTE.test(entry)) return entry;
  const base = projectDirectory.replace(/[\\/]+$/, '');
  return windows ? `${base}\\${entry.replace(/\//g, '\\')}` : `${base}/${entry}`;
}

function resolveEntries(spec: HookSpec, expectWindows: boolean): { readonly project: string; readonly entries: string[] } {
  const absolute = expectWindows ? WINDOWS_ABSOLUTE : POSIX_ABSOLUTE;
  if (!absolute.test(spec.projectDirectory) || spec.projectDirectory.includes('\0')) throw new Error(expectWindows ? 'Windows hooks require an absolute Windows project path' : 'POSIX hooks require an absolute POSIX project path');
  return { project: spec.projectDirectory, entries: spec.pathEntries.map(entry => joinEntry(spec.projectDirectory, entry)) };
}

export function renderPosixHook(spec: HookSpec): HookResult {
  try {
    const { project, entries } = resolveEntries(spec, false);
    const functions = entries.map((entry, index) => `_stackmanage_prepend_${index}() {\n  [ -d ${shQuote(entry)} ] || return 0\n  case ":\${PATH}:" in\n    *":${entry.replace(/[\\"$`]/g, ch => `\\${ch}`)}:"*) return 0 ;;\n  esac\n  PATH=${shQuote(entry)}":\${PATH}"\n  export PATH\n}`);
    const calls = entries.map((_entry, index) => `_stackmanage_prepend_${index}`);
    const lines = [
      HOOK_MARKER_BEGIN,
      '# Generated by StackManage. Remove everything between the markers to uninstall.',
      `export ${HOOK_ENV}=${shQuote(project)}`,
      ...functions,
      ...calls,
      'unset -f ' + calls.join(' ') + ' 2>/dev/null || true',
      HOOK_MARKER_END,
      ''
    ];
    return { ok: true, content: lines.join('\n') };
  } catch (error) {
    return { ok: false, reason: (error as Error).message };
  }
}

export function renderFishHook(spec: HookSpec): HookResult {
  try {
    const { project, entries } = resolveEntries(spec, false);
    const lines = [
      HOOK_MARKER_BEGIN,
      '# Generated by StackManage. Remove everything between the markers to uninstall.',
      `set -gx ${HOOK_ENV} ${fishQuote(project)}`,
      ...entries.map(entry => `if test -d ${fishQuote(entry)}; and not contains -- ${fishQuote(entry)} $PATH\n    set -gx PATH ${fishQuote(entry)} $PATH\nend`),
      HOOK_MARKER_END,
      ''
    ];
    return { ok: true, content: lines.join('\n') };
  } catch (error) {
    return { ok: false, reason: (error as Error).message };
  }
}

export function renderPowerShellHook(spec: HookSpec): HookResult {
  try {
    const { project, entries } = resolveEntries(spec, true);
    const lines = [
      HOOK_MARKER_BEGIN,
      `$env:${HOOK_ENV} = ${psQuoteDouble(project)}`,
      ...entries.map(entry => `if (Test-Path -LiteralPath ${psQuoteDouble(entry)} -PathType Container) { if (-not (($env:PATH -split ';') -icontains ${psQuoteDouble(entry)})) { $env:PATH = ${psQuoteDouble(entry)} + ';' + $env:PATH } }`),
      HOOK_MARKER_END,
      ''
    ];
    return { ok: true, content: lines.join('\n') };
  } catch (error) {
    return { ok: false, reason: (error as Error).message };
  }
}

/**
 * cmd.exe hook. The language cannot escape `%` inside a value safely, so a
 * project path containing it is rejected instead of being emitted incorrectly.
 */
export function renderCmdHook(spec: HookSpec): HookResult {
  try {
    const { project, entries } = resolveEntries(spec, true);
    for (const entry of [project, ...entries]) cmdQuote(entry);
    const lines = [
      '@echo off',
      `rem ${HOOK_MARKER_BEGIN.slice(2, -3).trim()}`,
      `set "${HOOK_ENV}=${project}"`,
      ...entries.map(entry => `set "PATH=${entry};%PATH%"`),
      `rem ${HOOK_MARKER_END.slice(2, -3).trim()}`,
      ''
    ];
    return { ok: true, content: lines.join('\n') };
  } catch (error) {
    return { ok: false, reason: (error as Error).message };
  }
}

export function renderHook(shell: HookShell, spec: HookSpec): HookResult {
  switch (shell) {
    case 'bash':
    case 'zsh':
      return renderPosixHook(spec);
    case 'fish':
      return renderFishHook(spec);
    case 'powershell':
      return renderPowerShellHook(spec);
    case 'cmd':
      return renderCmdHook(spec);
  }
}

/** Extracts the managed hook block, or `undefined` when absent. Throws on duplicated or unbalanced markers. */
export function extractHookBlock(content: string): string | undefined {
  const lines = content.split(/\r?\n/);
  const begins: number[] = [];
  const ends: number[] = [];
  lines.forEach((line, index) => {
    if (line.trim() === HOOK_MARKER_BEGIN) begins.push(index);
    if (line.trim() === HOOK_MARKER_END) ends.push(index);
  });
  if (begins.length === 0 && ends.length === 0) return undefined;
  if (begins.length !== 1 || ends.length !== 1) throw new Error('hook markers are duplicated or unbalanced');
  const begin = begins[0] as number;
  const end = ends[0] as number;
  if (end <= begin) throw new Error('hook markers are out of order');
  return lines.slice(begin, end + 1).join('\n');
}

export type ShellRoundTrip = { readonly projectDirectory: string; readonly pathEntries: readonly string[] };

/**
 * Round-trip parser for generated POSIX and fish hooks. It reads only the
 * quoted values produced above and throws on anything else.
 */
export function parseHook(content: string, shell: 'bash' | 'zsh' | 'fish'): ShellRoundTrip {
  const block = extractHookBlock(content);
  if (block === undefined) throw new Error('no hook block');
  if (shell === 'fish') {
    const envLine = new RegExp(`set -gx ${HOOK_ENV} ('(?:[^'\\\\]|\\\\.)*')`).exec(block);
    if (!envLine) throw new Error('missing project directory');
    const project = fishUnquote(envLine[1] as string);
    const entries = [...block.matchAll(/test -d ('(?:[^'\\]|\\.)*')/g)].map(m => fishUnquote(m[1] as string));
    return { projectDirectory: project, pathEntries: entries };
  }
  const envLine = new RegExp(`export ${HOOK_ENV}=('(?:[^']|'\\\\'')*')`).exec(block);
  if (!envLine) throw new Error('missing project directory');
  const project = shUnquote(envLine[1] as string);
  const entries = [...block.matchAll(/\[ -d ('(?:[^']|'\\'')*') \]/g)].map(m => shUnquote(m[1] as string));
  return { projectDirectory: project, pathEntries: entries };
}
